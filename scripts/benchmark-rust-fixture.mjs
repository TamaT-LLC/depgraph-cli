#!/usr/bin/env node

import { mkdirSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";

export const RUST_BENCHMARK_SOURCE_FILES = 31;
export const RUST_BENCHMARK_FUNCTIONS_PER_MODULE = 84;
export const RUST_BENCHMARK_SCHEMA_VERSION =
  "depgraph-rust-hir-benchmark-fixture-v1";

function moduleName(index) {
  return `module_${String(index).padStart(2, "0")}`;
}

function moduleSource(moduleIndex) {
  const name = moduleName(moduleIndex);
  const functions = Array.from(
    { length: RUST_BENCHMARK_FUNCTIONS_PER_MODULE },
    (_, functionIndex) => {
      const suffix = String(functionIndex).padStart(3, "0");
      return `pub fn ${name}_transform_${suffix}(input: Input) -> Output {\n    transform(input)\n}\n`;
    },
  );
  return `use crate::{transform, Input, Output};\n\n${functions.join("\n")}`;
}

export function generateRustFixture(root) {
  root = resolve(root);
  mkdirSync(root);
  mkdirSync(join(root, "src"));

  writeFileSync(
    join(root, "Cargo.toml"),
    `[package]\nname = "depgraph-rust-hir-benchmark"\nversion = "0.1.0"\nedition = "2024"\n`,
  );
  writeFileSync(
    join(root, "Cargo.lock"),
    `# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = "depgraph-rust-hir-benchmark"\nversion = "0.1.0"\n`,
  );

  const moduleCount = RUST_BENCHMARK_SOURCE_FILES - 1;
  const declarations = Array.from(
    { length: moduleCount },
    (_, index) => `pub mod ${moduleName(index)};`,
  );
  const library = `\
${declarations.join("\n")}

#[derive(Clone, Copy)]
pub struct Input {
    pub value: u64,
}

#[derive(Clone, Copy)]
pub struct Output {
    pub value: u64,
}

pub fn transform(input: Input) -> Output {
    Output { value: input.value }
}
`;
  writeFileSync(join(root, "src/lib.rs"), library);
  for (let index = 0; index < moduleCount; index += 1) {
    writeFileSync(
      join(root, `src/${moduleName(index)}.rs`),
      moduleSource(index),
    );
  }

  return {
    schema_version: RUST_BENCHMARK_SCHEMA_VERSION,
    source_file_count: RUST_BENCHMARK_SOURCE_FILES,
    generated_function_count:
      moduleCount * RUST_BENCHMARK_FUNCTIONS_PER_MODULE,
    expected_semantic_site_floor:
      moduleCount * RUST_BENCHMARK_FUNCTIONS_PER_MODULE * 3,
  };
}

function main(argv) {
  const [command, root, ...extra] = argv;
  if (command !== "generate" || !root || extra.length !== 0) {
    throw new Error("usage: benchmark-rust-fixture.mjs generate ROOT");
  }
  process.stdout.write(`${JSON.stringify(generateRustFixture(root))}\n`);
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(resolve(process.argv[1])).href
) {
  try {
    main(process.argv.slice(2));
  } catch (error) {
    process.stderr.write(`${error.stack ?? error}\n`);
    process.exitCode = 1;
  }
}
